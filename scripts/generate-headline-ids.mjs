import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { pathToFileURL } from "node:url";

import {
  HEADLINE_UUID_NAMESPACE,
  defaultHeadlineContent,
  headlineVariantContent,
} from "../src/features/landing/data/headline-content.ts";

/** UUIDv5: stable IDs from ordered segment text; emphasis and rarity are ignored. */
export function generateHeadlineId(segments) {
  const namespace = Buffer.from(HEADLINE_UUID_NAMESPACE.replaceAll("-", ""), "hex");
  const name = Buffer.from(JSON.stringify(segments.map(({ text }) => text)), "utf8");
  const hash = createHash("sha1").update(namespace).update(name).digest();
  hash[6] = (hash[6] & 0x0f) | 0x50;
  hash[8] = (hash[8] & 0x3f) | 0x80;
  const hex = hash.subarray(0, 16).toString("hex");
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

export function generateHeadlineIds() {
  const headlines = [defaultHeadlineContent, ...headlineVariantContent];
  const ids = headlines.map(({ segments }) => generateHeadlineId(segments));
  const seen = new Set();

  for (const id of ids) {
    if (seen.has(id)) throw new Error(`Duplicate headline text generates UUID ${id}`);
    seen.add(id);
  }

  return ids;
}

async function writeGeneratedIds() {
  const ids = generateHeadlineIds();
  const outputPath = resolve("src/features/landing/data/headline-ids.generated.ts");
  await mkdir(dirname(outputPath), { recursive: true });
  const contents = `// Generated by scripts/generate-headline-ids.mjs. Do not edit manually.\nexport const generatedHeadlineIds = ${JSON.stringify(ids, null, 2)} as const;\n`;
  await writeFile(outputPath, contents, "utf8");
  console.log(`Generated ${ids.length} stable headline UUIDs.`);
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  await writeGeneratedIds();
}
